TEXT_TYPES = ("public.utf8-plain-text", "public.utf16-plain-text", "public.utf16-external-plain-text",
              "public.plain-text", "public.text", "public.utf8-tab-separated-values-text",
              "public.url", "public.file-url", "public.html", "public.rtf")
IGNORED_TYPES = {"org.nspasteboard.concealedtype", "org.nspasteboard.transienttype",
                 "org.nspasteboard.autogeneratedtype", "org.chromium.internal.source-rfh-token"}
PRIVATE_FLAGS = ("withheld", "secret", "sensitive", "concealed", "excluded")
CREDENTIAL_KEYS = {"authorization", "apikey", "accesstoken", "refreshtoken", "clientsecret",
                   "privatekey", "password", "secret"}
MAX_DOCUMENT = 128 * 1024 * 1024


@lru_cache(maxsize=1)
def recording_source():
    # The producer's own validator covers v1–v3, digest binding, unique IDs and span bounds.
    spec = importlib.util.spec_from_file_location(
        "_hub_recording_source", data_file("channels/audio/record-for-agent/AgentBridge/library.py"))
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


def read_bytes(path, maximum=MAX_DOCUMENT):
    with path.open("rb") as source:
        if os.fstat(source.fileno()).st_size > maximum:
            raise ValueError("Selected JSON file exceeds the import size limit.")
        data = source.read(maximum + 1)
        if len(data) > maximum:
            raise ValueError("Selected JSON file exceeds the import size limit.")
        return data


def document(data):
    try:
        return recording_source().parse_json(data)
    except recording_source().BridgeError as error:
        raise ValueError(str(error)) from None


def timestamp(value):
    instant = datetime.fromisoformat(value.replace("Z", "+00:00"))
    if instant.tzinfo is None:
        raise ValueError("Producer timestamps must include their UTC offset.")
    return round(instant.timestamp() * 1000)


def withheld(value):
    if not isinstance(value, dict):
        return False
    if any(value.get(key) is True for key in PRIVATE_FLAGS) or value.get("shared") is False:
        return True
    privacy = value.get("privacy")
    if isinstance(privacy, dict):
        if any(privacy.get(key) is True for key in PRIVATE_FLAGS):
            return True
        tags = privacy.get("pii_tags") or []
        return any(str(tag).casefold() in {"secret", "password", "credential", "api_key", "access_token"}
                   for tag in tags)
    return False


def public_fields(value):
    """Generic events may carry additional metadata objects. Respect explicit field-level withholding."""
    if isinstance(value, dict):
        blocked = value.get("withheld_fields", [])
        if not isinstance(blocked, list) or not all(isinstance(key, str) for key in blocked):
            raise ValueError("withheld_fields must be a list of field names.")
        return {key: public_fields(child) for key, child in value.items()
                if key != "withheld_fields" and key not in blocked and not withheld(child)
                and key.replace("_", "").replace("-", "").casefold() not in CREDENTIAL_KEYS}
    if isinstance(value, list):
        return [public_fields(child) for child in value if not withheld(child)]
    return value


def safe_event(event):
    if not isinstance(event, dict):
        raise ValueError("Expected a ContextEvent object.")
    if withheld(event) or withheld(event.get("content")):
        return None
    return public_fields(event)


def stable_id(*parts):
    name = json.dumps(parts, ensure_ascii=False, separators=(",", ":"))
    return str(uuid.uuid5(uuid.NAMESPACE_URL, name))


def clipboard_event(item, device, archive_id, observed, tier, chunk_name=None, revision=None):
    if not isinstance(item, dict) or not isinstance(item.get("contents"), list):
        raise ValueError("Invalid clipboard item or contents.")
    if (withheld(item) or item.get("withheld_fields") or
            any(withheld(part) or part.get("withheld_fields") or part["type"].casefold() in IGNORED_TYPES
                for part in item["contents"])):
        return None
    original = item["id"]
    if not isinstance(original, str) or not original or not isinstance(item.get("title"), str):
        raise ValueError("Invalid clipboard item ID or title.")
    forms = []
    for part in item["contents"]:
        kind = part["type"]
        form = {"type": kind}
        if not isinstance(kind, str):
            raise ValueError("Invalid clipboard representation type.")
        data = None
        if "base64" in part:
            data = base64.b64decode(part["base64"], validate=True)
            form.update(byte_count=len(data), sha256=hashlib.sha256(data).hexdigest())
        if kind in TEXT_TYPES:
            if isinstance(part.get("text"), str):
                form["text"] = part["text"]
            elif data is not None:
                try:
                    form["text"] = data.decode("utf-16" if "utf16" in kind else "utf-8")
                except UnicodeError:
                    pass
        forms.append(form)
    preferred = next((part["text"] for kind in TEXT_TYPES for part in forms
                      if part["type"] == kind and part.get("text")), "")
    start, end = timestamp(item["firstCopiedAt"]), timestamp(item["lastCopiedAt"])
    if end < start:
        raise ValueError("Clipboard last copy precedes its first copy.")
    context = {key: item[key] for key in ("numberOfCopies", "pin", "originHistoryID", "origin",
                                            "originNumberOfCopies", "sequence") if key in item}
    if item.get("application") is not None:
        context["app_bundle"] = item["application"]
    locator = (chunk_name or "clipboard.json") + "#item=" + quote(original, safe="")
    scope = "raw/" + archive_id if archive_id else "snapshot"
    source_id = f"{quote(device, safe='')}/{scope}/{quote(original, safe='')}"
    provenance = {"connector": "ClipContext", "source_id": source_id,
                  "original_id": original, "locator": locator}
    if archive_id:
        provenance["archive_id"] = archive_id
        provenance["version"] = "2"
    else:
        provenance.update(version="1", snapshot_revision=revision)
    return {"id": stable_id("clipcontext", device, archive_id, original),
            "source": "clipboard", "kind": "copy", "t_start": start, "t_end": end,
            "t_observed": observed, "device_id": device, "context": context,
            "content": {"title": item["title"], "text": preferred, "representations": forms},
            "provenance": provenance, "privacy": {"tier": tier}}


def clipboard_rows(path, data, tier):
    archive = document(data)
    device = archive["deviceID"]
    updated = timestamp(archive["updatedAt"])
    if not isinstance(device, str) or not device or type(archive.get("revision")) is not int or archive["revision"] < 0:
        raise ValueError("Invalid ClipContext archive header.")
    if archive.get("schemaVersion") == 1 and isinstance(archive.get("items"), list):
        for item in archive["items"]:
            yield clipboard_event(item, device, None, updated, tier, revision=archive["revision"])
        return
    if (archive.get("schemaVersion") != 2 or archive.get("archiveType") != "raw"
            or not isinstance(archive.get("chunks"), list) or archive.get("itemCount") != archive["revision"]):
        raise ValueError("Expected a ClipContext v1 snapshot or v2 raw manifest.")
    archive_id = str(uuid.UUID(archive["archiveID"]))
    seen = 0
    for index, descriptor in enumerate(archive["chunks"]):
        key = f"{index:08d}"
        name = f"chunks/{key}.json"
        count = descriptor["itemCount"]
        if (descriptor["key"] != key or descriptor["file"] != name or type(count) is not int
                or not 1 <= count <= 100 or descriptor["revision"] != seen + count):
            raise ValueError("Invalid ClipContext chunk descriptor.")
        # Open the canonical producer names only, disallowing symlinks at both child components.
        folder = os.open(path.parent / "chunks", os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW)
        try:
            fd = os.open(key + ".json", os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK, dir_fd=folder)
            with os.fdopen(fd, "rb") as source:
                if not stat.S_ISREG(os.fstat(fd).st_mode) or os.fstat(fd).st_size > MAX_DOCUMENT:
                    raise ValueError("Expected a bounded regular clipboard chunk.")
                encoded = source.read(MAX_DOCUMENT + 1)
        finally:
            os.close(folder)
        if len(encoded) > MAX_DOCUMENT or hashlib.sha256(encoded).hexdigest() != descriptor["sha256"].lower():
            raise ValueError("ClipContext chunk checksum mismatch.")
        chunk = document(encoded)
        if (chunk.get("schemaVersion") != 1 or chunk.get("deviceID") != device
                or chunk.get("revision") != descriptor["revision"] or len(chunk["items"]) != count):
            raise ValueError("ClipContext chunk metadata differs from the manifest.")
        for item in chunk["items"]:
            if not isinstance(item.get("contents"), list) or any(
                    not isinstance(part, dict) or not isinstance(part.get("base64"), str) for part in item["contents"]):
                raise ValueError("ClipContext raw content requires a binary representation.")
            seen += 1
            if item.get("sequence") != seen:
                raise ValueError("ClipContext raw event sequence differs from the manifest.")
            uuid.UUID(item["id"])
            # A growing final chunk can be rewritten; each individual event keeps its own copy time.
            yield clipboard_event(item, device, archive_id, timestamp(item["lastCopiedAt"]), tier, name)
    if seen != archive["itemCount"] or read_bytes(path) != data:
        raise ValueError("ClipContext raw manifest changed or was incomplete. Retry the import.")


def recording_rows(path, tier):
    source = recording_source()
    limits = source.Limits()
    try:
        if path.suffix.lower() == ".zip":
            # Verify the complete selected archive with the producer. Temporary CAFs are removed
            # on exit and neither their bytes nor filesystem paths are sent to the Hub.
            with tempfile.TemporaryDirectory() as staging:
                archive = source._stage_export(path, Path(staging), limits)
            verified_audio = True
        else:
            archive = source.validate_export(document(read_bytes(path, limits.max_metadata_bytes)), limits)
            verified_audio = False
    except source.BridgeError as error:
        raise ValueError(str(error)) from None
    for entry in archive["segments"]:
        m = entry["manifest"]
        transcript = entry.get("transcript")
        content = {"transcript_status": "ready" if transcript else "not_generated"}
        context = {key: m[key] for key in ("sessionID", "sequence", "sampleRate", "frameCount",
                                          "byteCount", "recordingGroup") if key in m}
        if transcript:
            content.update(text=transcript["text"], lang=transcript["locale"], spans=transcript["spans"],
                           transcript_engine=transcript["engine"], transcript_created_at=transcript["createdAt"])
        event = {"id": stable_id("record-for-agent", m["id"]), "kind": "transcript_segment" if transcript else "audio_segment",
                 "source": "voice", "t_start": m["startedAt"], "t_end": m["endedAt"], "t_observed": archive["exportedAt"],
                 "tz": m.get("timeZoneIdentifier", "UTC"), "tz_source": "recorded" if "timeZoneIdentifier" in m else "utc_fallback",
                 "content": content, "context": context, "privacy": {"tier": tier},
                 "provenance": {"connector": "record-for-agent", "source_id": m["id"],
                                "source_hash": m["sha256"], "locator": "export.json#segment=" + m["id"],
                                "export_id": archive["exportID"], "version": str(archive["schemaVersion"]),
                                "audio_member": entry["audioPath"],
                                "audio_bytes_verified": verified_audio}}
        if "location" in m:
            loc = m["location"]
            event["location"] = {"lat": loc["latitude"], "lon": loc["longitude"],
                                 "horizontalAccuracy": loc["horizontalAccuracy"], "capturedAt": loc["capturedAt"]}
        yield event


def import_file(client, path, source, tier=None, mode="local", update_existing=False):
    if mode not in {"local", "cloud"}:
        raise ValueError("HUB_MODE must be local or cloud.")
    remote = mode == "cloud" or client.cloud or not client.loopback
    if source == "context-event" and tier is not None:
        raise ValueError("ContextEvent imports preserve each event's own privacy tier.")
    if tier not in {None, "local_only", "shareable"}:
        raise ValueError("Choose local_only or explicitly shareable for native data.")
    if source != "context-event" and remote and tier != "shareable":
        raise ValueError("local_only cannot be sent to a remote or cloud Hub. Select shareable explicitly.")
    if source == "clipcontext":
        rows = clipboard_rows(path, read_bytes(path), tier or "local_only")
    elif source == "record-for-agent":
        rows = recording_rows(path, tier or "local_only")
    elif source == "context-event":
        payload = document(read_bytes(path))
        items = payload if isinstance(payload, list) else [payload]
        rows = (safe_event(item) for item in items)
    else:
        raise ValueError("Unknown source format.")
    counts = {"created": 0, "unchanged": 0, "updated": 0, "skipped": 0}
    seen = set()
    needs_local_destination = False
    # Validate the entire selection and all privacy tiers before any HTTP operation.
    with tempfile.TemporaryFile(mode="w+", encoding="utf-8") as staging:
        for row in rows:
            if row is None:
                counts["skipped"] += 1
                continue
            validate_event(row)
            if row["privacy"]["tier"] == "local_only":
                if remote:
                    raise ValueError("local_only cannot be sent to a remote or cloud Hub.")
                needs_local_destination = True
            if row["id"] in seen:
                raise ValueError("The selected export contains duplicate record IDs.")
            seen.add(row["id"])
            staging.write(json.dumps(row, ensure_ascii=False, allow_nan=False) + "\n")
        if needs_local_destination:
            client.require_local_destination()
        staging.seek(0)
        for line in staging:
            row = json.loads(line)
            try:
                existing = client.one("GET", "raw", row["id"])
            except HubError as error:
                if error.status != 404:
                    raise
                client.request("POST", "/api/raw", row)
                counts["created"] += 1
                continue
            normalized = {**row, "t_observed": existing["t_observed"]}
            if source == "clipcontext" and "snapshot_revision" in row["provenance"]:
                # The archive revision changes when any item changes. Keep the first observed
                # revision of an identical item, so an unrelated copy does not rewrite all rows.
                normalized["provenance"] = {**row["provenance"],
                                            "snapshot_revision": existing["provenance"].get("snapshot_revision")}
            if {k: v for k, v in existing.items() if k != "revision"} == normalized:
                counts["unchanged"] += 1
                continue
            if not update_existing:
                raise ValueError(f"Existing event {row['id']} differs. Review it, then use --update-existing to replace it.")
            client.one("PUT", "raw", row["id"], {**row, "revision": existing["revision"]})
            counts["updated"] += 1
    return counts


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, epilog=(
        "Select only the published clipboard.json or Raw/manifest.json, the iPhone's selected "
        "Record-for-Agent ZIP/export.json, or an explicit ContextEvent object/array. No watchers. "
        "Native selections are local_only unless marked --privacy shareable. The importer keeps "
        "clipboard text and binary digests, and recording metadata/transcripts/spans and audio digests. "
        "ZIP verifies original CAFs; standalone export.json verifies metadata binding only. "
        "HUB_URL defaults to loopback. Remote requires HTTPS. The Hub health endpoint is checked before sending local-only data, including over tunnels. "
        "Use HUB_OWNER_TOKEN, never the agent token. A retry skips identical events."))
    parser.add_argument("format", choices=["clipcontext", "record-for-agent", "context-event"])
    parser.add_argument("file", type=Path, help="One explicit export file")
    parser.add_argument("--privacy", choices=["local_only", "shareable"])
    parser.add_argument("--update-existing", action="store_true", help="Replace changed records at their observed revisions")
    args = parser.parse_args(argv)
    try:
        client = HubClient(os.environ.get("HUB_URL", DEFAULT_URL), os.environ.get("HUB_OWNER_TOKEN"))
        result = import_file(client, args.file, args.format, args.privacy,
                             os.environ.get("HUB_MODE", "local"), args.update_existing)
    except (ValueError, KeyError, TypeError, AttributeError, OSError) as error:
        parser.exit(1, f"Import failed: {error}\n")
    print(json.dumps(result, ensure_ascii=False))


if __name__ == "__main__":
    main()
