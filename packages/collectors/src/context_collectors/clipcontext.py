"""Incremental ClipContext Clipboard Collector with Anti-Rollback & Revocation Sync.

Supports both ClipContext formats:
1. `Agent/clipboard.json` (ClipContext 0.1.1 versioned atomic snapshot: `deviceID`, `revision`, `items[]`).
2. `Raw/manifest.json` + `Raw/chunks/*.json` / `*.jsonl` (chunked archive format).

Safety guarantees:
- Anti-rollback guard: rejects snapshots from the same `deviceID` whose `revision` is
  lower than the last synced revision (prevents iCloud stale-file overwrites).
- Per-item SHA-256 fingerprinting: emits only genuinely new/updated entries and propagates
  revoked/deleted items to Hub via `sink.revoke(...)`.
- Pasteboard firewall: drops concealed/transient UTIs and password-manager bundle IDs
  before events ever leave the collector (Hub's own secret firewall acts as second barrier).
"""

from __future__ import annotations

import base64
import datetime
import hashlib
import json
import os
import re
from pathlib import Path
from typing import Any

from context_hub.models import RawEventIn

from .runtime import CheckpointBackend, HubSink, SyncReport, default_device_id

_CONCEALED_UTIS = {
    "org.nspasteboard.concealedtype",
    "org.nspasteboard.transienttype",
    "org.nspasteboard.autogeneratedtype",
    "de.petermaurer.transientpasteboardtype",
    "com.typeit4me.clipping",
    "nspasteboardtypeconcealed",
}

_SENSITIVE_BUNDLE_PREFIXES = (
    "com.agilebits.onepassword",
    "com.1password.",
    "com.bitwarden.",
    "com.apple.keychainaccess",
    "com.apple.passwords",
    "com.lastpass.",
    "com.dashlane.",
    "org.keepassxc.",
)

_TEXT_UTI_PRIORITY = (
    "public.utf8-plain-text",
    "public.plain-text",
    "public.text",
    "public.url",
    "public.file-url",
    "public.utf16-plain-text",
    "public.utf16-external-plain-text",
    "public.html",
)

_DECODABLE_TEXT_UTIS = {
    "public.utf8-plain-text",
    "public.plain-text",
    "public.text",
    "public.url",
    "public.file-url",
    "org.chromium.source-url",
    "public.utf16-plain-text",
    "public.utf16-external-plain-text",
    "public.utf8-tab-separated-values-text",
    "public.html",
}

_UTF16_UTIS = {
    "public.utf16-plain-text",
    "public.utf16-external-plain-text",
}

_MAX_BASE64_TEXT_CHARS = 2_000_000
_HTTP_URL_RE = re.compile(r"^https?://\S+$", re.I)
_URL_ONLY_RE = _HTTP_URL_RE
_CODE_HINT_RE = re.compile(
    r"(?:^\s*(?:def |class |function |const |let |import |export |SELECT |curl |git |uv |npm |docker )|[{};]=>|```)",
    re.M,
)


def default_clipcontext_paths(home: Path | None = None) -> tuple[Path, Path]:
    h = (home or Path.home()).expanduser()
    base = h / "Library" / "Application Support" / "ClipContext"
    snapshot = Path(
        os.environ.get("CONTEXT_CLIPCONTEXT_SNAPSHOT", str(base / "Agent" / "clipboard.json"))
    ).expanduser()
    raw_manifest = Path(
        os.environ.get("CONTEXT_CLIPCONTEXT_MANIFEST", str(base / "Raw" / "manifest.json"))
    ).expanduser()
    return snapshot, raw_manifest


def _iso_to_ms(value: Any) -> int:
    if isinstance(value, (int, float)):
        return round(value if abs(value) >= 100_000_000_000 else value * 1000)
    if isinstance(value, str) and value.strip():
        dt = datetime.datetime.fromisoformat(value.strip().replace("Z", "+00:00"))
        if dt.tzinfo is None:
            dt = dt.replace(tzinfo=datetime.UTC)
        return round(dt.timestamp() * 1000)
    return 0


def _fingerprint(obj: Any) -> str:
    encoded = json.dumps(obj, ensure_ascii=True, sort_keys=True, separators=(",", ":")).encode(
        "ascii"
    )
    return hashlib.sha256(encoded).hexdigest()


def _is_blocked_item(item: dict[str, Any]) -> bool:
    app = str(item.get("application") or "").strip().lower()
    if any(app.startswith(prefix) for prefix in _SENSITIVE_BUNDLE_PREFIXES):
        return True
    for part in item.get("contents") or []:
        if not isinstance(part, dict):
            continue
        uti = str(part.get("type") or "").strip().lower()
        if uti in _CONCEALED_UTIS:
            return True
    return False


def _decode_part_text(part: dict[str, Any], uti: str) -> str:
    """Return decoded text from `part['text']`, falling back to `part['base64']` for text/URL UTIs."""
    txt = part.get("text")
    if isinstance(txt, str) and txt.strip():
        return txt.strip()
    if uti not in _DECODABLE_TEXT_UTIS:
        return ""
    b64 = part.get("base64")
    if not isinstance(b64, str) or not b64.strip() or len(b64) > _MAX_BASE64_TEXT_CHARS:
        return ""
    try:
        raw = base64.b64decode(b64, validate=False)
    except (ValueError, TypeError):
        return ""
    if not raw:
        return ""
    if uti in _UTF16_UTIS:
        encoding = "utf-16" if raw.startswith((b"\xff\xfe", b"\xfe\xff")) else "utf-16-le"
        decoded = raw.decode(encoding, errors="ignore")
    else:
        decoded = raw.decode("utf-8", errors="ignore")
    return decoded.replace("\x00", "").strip()


def _extract_preferred_text_and_url(
    item: dict[str, Any],
) -> tuple[str, str | None, str | None, bool]:
    """Return `(text, url, source_url, has_image)` from ClipContext `contents[]` parts."""
    by_uti: dict[str, str] = {}
    source_url: str | None = None
    has_image = False
    for part in item.get("contents") or []:
        if not isinstance(part, dict):
            continue
        uti = str(part.get("type") or "").strip().lower()
        if any(img in uti for img in ("png", "jpeg", "tiff", "heic", "webp", "image")):
            has_image = True
        decoded = _decode_part_text(part, uti)
        if not decoded:
            continue
        if uti == "org.chromium.source-url":
            if not source_url and _HTTP_URL_RE.match(decoded):
                source_url = decoded
            continue
        if uti not in by_uti:
            by_uti[uti] = decoded

    chosen_text = ""
    for uti in _TEXT_UTI_PRIORITY:
        if uti in by_uti:
            chosen_text = by_uti[uti]
            break
    if not chosen_text and by_uti:
        chosen_text = next(iter(by_uti.values()))
    if not chosen_text and isinstance(item.get("text"), str):
        chosen_text = item["text"].strip()
    if not chosen_text and isinstance(item.get("title"), str):
        chosen_text = item["title"].strip()

    url: str | None = by_uti.get("public.url")
    if not url and chosen_text and _URL_ONLY_RE.match(chosen_text):
        url = chosen_text
    return chosen_text, url, source_url, has_image


def _classify_clipboard_content(text: str, url: str | None, has_image: bool) -> str:
    if url and (not text or text.strip() == url.strip()):
        return "url"
    if not text and has_image:
        return "image_meta"
    if text and _CODE_HINT_RE.search(text):
        return "code"
    return "text"


def _item_to_event(
    item: dict[str, Any],
    *,
    device_id: str,
    locator_prefix: str,
) -> RawEventIn | None:
    if _is_blocked_item(item):
        return None
    item_id = str(item.get("id") or "").strip()
    if not item_id:
        return None
    text, url, source_url, has_image = _extract_preferred_text_and_url(item)
    if not text and not has_image:
        return None

    t_first = _iso_to_ms(item.get("firstCopiedAt") or item.get("lastCopiedAt"))
    t_last = _iso_to_ms(item.get("lastCopiedAt") or item.get("firstCopiedAt"))
    if t_last < t_first:
        t_last = t_first
    clip_type = _classify_clipboard_content(text, url, has_image)
    title = str(item.get("title") or "").strip() or (
        text.splitlines()[0][:100] if text else f"[Image copy] {item_id}"
    )

    content: dict[str, Any] = {
        "title": title[:200],
        "text": text or f"[Clipboard image from {item.get('application') or 'unknown'}]",
        "clip_type": clip_type,
        "has_image": has_image,
    }
    if url:
        content["url"] = url
    if source_url:
        content["source_url"] = source_url

    context: dict[str, Any] = {
        "app_bundle": item.get("application"),
        "number_of_copies": int(item.get("numberOfCopies") or 1),
        "pinned": bool(item.get("pin")),
    }
    if source_url:
        context["source_url"] = source_url
    if item.get("sequence") is not None:
        context["sequence"] = int(item["sequence"])
    if item.get("origin"):
        context["origin"] = str(item["origin"])
    if item.get("originHistoryID"):
        context["origin_history_id"] = str(item["originHistoryID"])
    if bool(item.get("pin")) or int(item.get("numberOfCopies") or 1) >= 2:
        context["curation_tier"] = "auto_curated"

    return RawEventIn(
        source="clipboard",
        kind="copy",
        t_start=t_first,
        t_end=t_last,
        device_id=device_id,
        actor="self",
        content=content,
        context=context,
        provenance={
            "connector": "clipcontext",
            "source_id": f"{device_id}:{item_id}",
            "locator": f"{locator_prefix}#item={item_id}",
        },
    )


class ClipContextCollector:
    """Incremental ClipContext collector supporting snapshot JSON & chunked Raw manifests."""

    name = "clipcontext"
    source = "clipboard"

    def __init__(
        self,
        *,
        snapshot_path: Path | None = None,
        raw_manifest_path: Path | None = None,
    ):
        default_snap, default_manifest = default_clipcontext_paths()
        self.snapshot_path = snapshot_path if snapshot_path is not None else default_snap
        self.raw_manifest_path = (
            raw_manifest_path if raw_manifest_path is not None else default_manifest
        )

    def doctor(self) -> dict[str, Any]:
        snap_ok = bool(self.snapshot_path and self.snapshot_path.is_file())
        manifest_ok = bool(self.raw_manifest_path and self.raw_manifest_path.is_file())
        info: dict[str, Any] = {
            "collector": self.name,
            "snapshot": {
                "path": str(self.snapshot_path),
                "available": snap_ok,
            },
            "raw_manifest": {
                "path": str(self.raw_manifest_path),
                "available": manifest_ok,
            },
        }
        if snap_ok and self.snapshot_path:
            try:
                data = json.loads(self.snapshot_path.read_text(encoding="utf-8"))
                info["snapshot"]["device_id"] = data.get("deviceID")
                info["snapshot"]["revision"] = data.get("revision")
                info["snapshot"]["item_count"] = len(data.get("items") or [])
            except (OSError, ValueError) as exc:
                info["snapshot"]["error"] = str(exc)
        if manifest_ok and self.raw_manifest_path:
            try:
                mdata = json.loads(self.raw_manifest_path.read_text(encoding="utf-8"))
                info["raw_manifest"]["device_id"] = mdata.get("deviceID") or mdata.get("device_id")
                info["raw_manifest"]["revision"] = mdata.get("revision")
                info["raw_manifest"]["item_count"] = mdata.get("itemCount")
                info["raw_manifest"]["chunk_count"] = len(mdata.get("chunks") or [])
            except (OSError, ValueError) as exc:
                info["raw_manifest"]["error"] = str(exc)
        return info

    def _sync_snapshot_json(
        self,
        path: Path,
        sink: HubSink,
        checkpoints: CheckpointBackend,
        report: SyncReport,
    ) -> None:
        report.sources_scanned += 1
        source_key = f"snapshot:{path}"
        cp = checkpoints.get(self.name, source_key)
        st = path.stat()
        if (
            cp
            and int(cp.get("inode") or 0) == st.st_ino
            and int(cp.get("file_size") or 0) == st.st_size
            and int(cp.get("mtime_ns") or 0) == st.st_mtime_ns
        ):
            report.sources_unchanged += 1
            return

        archive = json.loads(path.read_text(encoding="utf-8"))
        device_id = str(archive.get("deviceID") or default_device_id())
        revision = int(archive.get("revision") or 0)
        items = archive.get("items") or []
        if not isinstance(items, list):
            raise ValueError("ClipContext snapshot `items` must be a list.")

        prev_cursor = (cp or {}).get("cursor") or {}
        same_device = prev_cursor.get("device_id") == device_id
        prev_rev = int(prev_cursor.get("revision") or 0)
        if same_device and revision < prev_rev:
            report.status = "degraded"
            msg = (
                f"Rejected stale ClipContext snapshot rollback "
                f"(revision {revision} < last synced {prev_rev} for device {device_id})"
            )
            report.errors.append(msg)
            report.message = msg
            return

        prior_fps: dict[str, str] = prev_cursor.get("fingerprints") if same_device else {}
        current_items: dict[str, dict[str, Any]] = {}
        current_fps: dict[str, str] = {}
        for item in items:
            if isinstance(item, dict) and item.get("id"):
                iid = str(item["id"])
                current_items[iid] = item
                current_fps[iid] = _fingerprint(item)

        # 1. Emit new or updated items
        events: list[RawEventIn] = []
        for iid, item in current_items.items():
            if prior_fps.get(iid) == current_fps[iid]:
                continue
            ev = _item_to_event(
                item,
                device_id=device_id,
                locator_prefix="clipcontext://Agent/clipboard.json",
            )
            if ev is not None:
                events.append(ev)

        if events:
            report.events_emitted += len(events)
            res = sink.emit_batch(self.name, events)
            report.created += res.get("created", 0)
            report.existing += res.get("existing", 0)
            report.spooled += res.get("spooled", 0)

        # 2. Propagate revoked / deleted clipboard items
        revoked_ids = sorted(set(prior_fps.keys()) - set(current_fps.keys()))
        for rid in revoked_ids:
            if sink.revoke("clipboard", "clipcontext", f"{device_id}:{rid}"):
                report.revoked += 1

        checkpoints.put(
            self.name,
            source_key,
            device_id=device_id,
            inode=st.st_ino,
            file_size=st.st_size,
            mtime_ns=st.st_mtime_ns,
            cursor={
                "device_id": device_id,
                "revision": revision,
                "fingerprints": current_fps,
            },
        )
        report.watermark = f"device={device_id},rev={revision}"

    def _sync_raw_manifest(
        self,
        manifest_path: Path,
        sink: HubSink,
        checkpoints: CheckpointBackend,
        report: SyncReport,
    ) -> None:
        report.sources_scanned += 1
        source_key = f"manifest:{manifest_path}"
        cp = checkpoints.get(self.name, source_key)
        st = manifest_path.stat()
        if (
            cp
            and int(cp.get("inode") or 0) == st.st_ino
            and int(cp.get("file_size") or 0) == st.st_size
            and int(cp.get("mtime_ns") or 0) == st.st_mtime_ns
        ):
            report.sources_unchanged += 1
            return

        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
        device_id = str(manifest.get("deviceID") or manifest.get("device_id") or default_device_id())
        archive_id = str(manifest.get("archiveID") or manifest.get("archive_id") or "")
        revision = int(manifest.get("revision") or 0)
        chunks_dir = manifest_path.parent / "chunks"
        chunk_entries = manifest.get("chunks") or []
        prev_cursor = (cp or {}).get("cursor") or {}
        prev_archive_id = str(prev_cursor.get("archive_id") or "")
        same_device = prev_cursor.get("device_id") == device_id
        same_archive = not archive_id or not prev_archive_id or prev_archive_id == archive_id
        same_stream = same_device and same_archive
        prev_rev = int(prev_cursor.get("revision") or 0)
        if same_stream and revision < prev_rev:
            report.status = "degraded"
            msg = (
                f"Rejected stale ClipContext Raw manifest rollback "
                f"(revision {revision} < last synced {prev_rev} for device {device_id})"
            )
            report.errors.append(msg)
            report.message = msg
            return

        seen_chunks: dict[str, str] = dict(prev_cursor.get("chunk_hashes") or {}) if same_stream else {}
        prev_chunk_item_ids: dict[str, list[str]] = (
            {
                str(k): [str(i) for i in v]
                for k, v in (prev_cursor.get("chunk_item_ids") or {}).items()
                if isinstance(v, list)
            }
            if same_stream
            else {}
        )
        new_seen_chunks: dict[str, str] = {}
        new_chunk_item_ids: dict[str, list[str]] = {}

        for entry in chunk_entries:
            chunk_name = entry.get("file") if isinstance(entry, dict) else str(entry)
            declared_sha = str(entry.get("sha256") or "") if isinstance(entry, dict) else ""
            if not chunk_name:
                continue
            chunk_path = chunks_dir / Path(chunk_name).name
            if not chunk_path.is_file() or chunk_path.is_symlink():
                continue
            cst = chunk_path.stat()
            chunk_sig = declared_sha or f"size:{cst.st_size}:mtime:{cst.st_mtime_ns}"
            if (
                seen_chunks.get(chunk_path.name) == chunk_sig
                and chunk_path.name in prev_chunk_item_ids
            ):
                new_seen_chunks[chunk_path.name] = chunk_sig
                new_chunk_item_ids[chunk_path.name] = prev_chunk_item_ids[chunk_path.name]
                continue

            raw_text = chunk_path.read_text(encoding="utf-8")
            parsed_items: list[dict[str, Any]] = []
            if chunk_path.suffix == ".jsonl":
                for line in raw_text.splitlines():
                    if line.strip():
                        obj = json.loads(line)
                        if isinstance(obj, dict):
                            parsed_items.append(obj)
            else:
                obj = json.loads(raw_text)
                if isinstance(obj, list):
                    parsed_items = [x for x in obj if isinstance(x, dict)]
                elif isinstance(obj, dict) and isinstance(obj.get("items"), list):
                    parsed_items = [x for x in obj["items"] if isinstance(x, dict)]

            chunk_events: list[RawEventIn] = []
            chunk_ids: list[str] = []
            for item in parsed_items:
                ev = _item_to_event(
                    item,
                    device_id=device_id,
                    locator_prefix=f"clipcontext://Raw/chunks/{chunk_path.name}",
                )
                if ev is not None:
                    chunk_events.append(ev)
                    chunk_ids.append(str(item["id"]).strip())

            # Stream chunk-by-chunk so large archives never accumulate every chunk in memory.
            if chunk_events:
                report.events_emitted += len(chunk_events)
                res = sink.emit_batch(self.name, chunk_events)
                report.created += res.get("created", 0)
                report.existing += res.get("existing", 0)
                report.spooled += res.get("spooled", 0)

            new_seen_chunks[chunk_path.name] = chunk_sig
            new_chunk_item_ids[chunk_path.name] = chunk_ids

        # Propagate deletions/revocations when items disappear across chunks or manifest drops a chunk.
        if same_stream and prev_chunk_item_ids:
            prior_all_ids = {iid for ids in prev_chunk_item_ids.values() for iid in ids}
            current_all_ids = {iid for ids in new_chunk_item_ids.values() for iid in ids}
            for rid in sorted(prior_all_ids - current_all_ids):
                if sink.revoke("clipboard", "clipcontext", f"{device_id}:{rid}"):
                    report.revoked += 1

        checkpoints.put(
            self.name,
            source_key,
            device_id=device_id,
            inode=st.st_ino,
            file_size=st.st_size,
            mtime_ns=st.st_mtime_ns,
            cursor={
                "device_id": device_id,
                "archive_id": archive_id,
                "revision": revision,
                "chunk_hashes": new_seen_chunks,
                "chunk_item_ids": new_chunk_item_ids,
            },
        )
        report.watermark = f"raw_device={device_id},rev={revision},chunks={len(new_seen_chunks)}"

    def sync(self, sink: HubSink, checkpoints: CheckpointBackend) -> SyncReport:
        report = SyncReport(collector=self.name, source=self.source)
        found_any = False

        if self.snapshot_path and self.snapshot_path.is_file():
            found_any = True
            self._sync_snapshot_json(self.snapshot_path, sink, checkpoints, report)

        if self.raw_manifest_path and self.raw_manifest_path.is_file():
            found_any = True
            self._sync_raw_manifest(self.raw_manifest_path, sink, checkpoints, report)

        if not found_any:
            report.status = "idle"
            report.message = (
                "No ClipContext archive found yet "
                f"(checked {self.snapshot_path} and {self.raw_manifest_path})"
            )
        elif not report.message:
            report.message = (
                f"ClipContext synced: created={report.created}, existing={report.existing}, "
                f"revoked={report.revoked}"
            )
        return report
